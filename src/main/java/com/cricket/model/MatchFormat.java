package com.cricket.model;

/**
 * Enum representing the format of a cricket match.
 */
public enum MatchFormat {
    TEST,   // 5-day Test match (unlimited overs)
    ODI,    // One Day International (50 overs per side)
    T20,    // Twenty20 match (20 overs per side)
    T10     // Ten-over match
}

